-- Catalog identity and reviewed beer versions.
-- A beer is identified by the immutable brewery + brand + beer name tuple.

alter table public.beers
  add column if not exists is_catalog boolean not null default false,
  add column if not exists catalog_confirmed_at timestamptz,
  add column if not exists catalog_confirmed_by uuid references auth.users(id) on delete set null,
  add column if not exists created_by uuid references auth.users(id) on delete set null;

comment on column public.beers.is_catalog is
  'True after the catalog administrator has reviewed and confirmed this beer as an autocomplete reference.';

create unique index if not exists beers_identity_unique_idx
  on public.beers (brewery_id, brand_id, lower(trim(name)))
  where brand_id is not null;

create or replace function private.guard_catalog_beer_update()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_user_id uuid := auth.uid();
  v_admin_id constant uuid := '17be5dc3-a3f9-4fd2-ae90-dee7692034fc';
begin
  if current_setting('beerapp.version_rpc', true) = 'on' or v_user_id = v_admin_id then
    return new;
  end if;

  if old.brewery_id is distinct from new.brewery_id
     or old.brand_id is distinct from new.brand_id
     or old.name is distinct from new.name then
    raise exception 'Pivovar, značka a název tvoří pevnou identitu piva.';
  end if;

  if v_user_id is null or not exists (
    select 1 from public.tastings
    where beer_id = old.id
      and user_id = v_user_id
      and tasted_on >= date '2026-09-01'
  ) then
    raise exception 'Upravit lze jen vlastní pivo ochutnané od 1. 9. 2026.';
  end if;

  if new.style_id is null or new.plato is null or new.abv is null then
    raise exception 'Pro novou verzi je povinný styl, stupňovitost a obsah alkoholu.';
  end if;

  return new;
end;
$function$;

drop trigger if exists beers_guard_catalog_update on public.beers;
create trigger beers_guard_catalog_update
before update on public.beers
for each row execute function private.guard_catalog_beer_update();

revoke all on function private.guard_catalog_beer_update() from public, anon, authenticated;

