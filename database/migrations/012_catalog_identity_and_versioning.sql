  add column if not exists ebc numeric,
  add column if not exists photo_url text,
  add column if not exists is_non_alcoholic boolean not null default false,
  add column if not exists created_by uuid references auth.users(id) on delete set null,
  add column if not exists supersedes_version_id bigint references public.beer_versions(id) on delete set null;

